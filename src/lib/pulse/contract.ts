// The /api/answer and /api/status contract, preserved from PULSE-Website.html.
// The export POSTed { guide, question, service, mode, history, draft } and read the fields below
// from the reply. Both the browser and the server import these types, so they cannot drift apart.

import type { GuideId } from "@/data/pulse/guides";
import type { ServiceId, SourceRecord } from "@/data/pulse/sources";

export const LIMITS = {
  question: 800,
  draft: 1200,
  /** Recent question-and-answer turns sent for follow-up context. */
  history: 8,
  historyAnswer: 4000,
} as const;

export type HistoryTurn = {
  question: string;
  answer: string;
  entry_ids: string[];
};

export type AnswerRequest = {
  guide: GuideId;
  question: string;
  service: ServiceId;
  mode: "live";
  history: HistoryTurn[];
  draft: string;
};

export type AnswerStatus = "answered" | "unknown" | "clarify" | "urgent";

export type AnswerResponse = {
  /** "live" = generated by the connected model. "system" = a labelled system or safety notice. */
  mode: "live" | "system";
  status: AnswerStatus;
  text: string;
  /** A must-read excerpt shown open under the answer. */
  essential?: { title: string; text: string };
  steps?: string[];
  /** A suggested first question the visitor can edit or copy. */
  draft?: string;
  /** Full source records, always rebuilt by the server from the register. */
  sources: SourceRecord[];
  entry_ids: string[];
  /** Extra detail shown under "About this answer". */
  notice?: string;
  /** Suggest switching to another personality. */
  switchTo?: GuideId;
  suggestions?: string[];
};

export type AnswerError = {
  error: string;
  code: "bad_request" | "not_configured" | "provider_error" | "invalid_output";
};

export type ConnectionStatus = {
  liveConfigured: boolean;
  /** Short machine-readable reason, e.g. "no-provider". */
  reason: string;
  /** Provider label when connected, e.g. "Anthropic". */
  provider?: string;
};
